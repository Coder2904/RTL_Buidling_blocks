module alu #(
    parameter WIDTH = 32
) 
(
    input wire [WIDTH-1:0] a, b,
    input wire [3:0] Operation_ctrl, /// Because we have 10 perations so to select them we need a 4-bit selection code
    output reg [WIDTH-1:0] result, /// Its reg type because its been used in always block for the cases of operation and storing their results
    output wire zero_flag, overflow_flag
);
///Opcodes ----> we have total 10 operations for ALU that's why  bit length of Operation_ctrl is 4
localparam ADD = 4'b0000, SUB = 4'b0001, AND_Op = 4'b0010, 
           OR_Op = 4'b0011, XOR_op = 4'b0100, SHIFT_LEFT_LOGICAl = 4'b0101,
           SHIFT_RIGHT_LOGICAL = 4'b0110, SHIFT_RIGHT_ARITHEMATIC = 4'b0111, 
           SET_LESS_THAN = 4'b1000, SET_LESS_THAN_UNsigned = 4'b1001;
 
localparam Shift_width = $clog2(WIDTH); /// this lets us know the bit lenght for shift amount 

// Internal wires
wire [WIDTH-1:0] b_bar, add_out, sub_out, and_out, or_out, xor_out,
                 sll_out, srl_out, sra_out;
wire            sub, is_addsub, carry_out, overflow, slt, sltu;
wire [Shift_width-1:0] shift_amount = b[Shift_width-1:0];  ///We have set the shift amount to be the lower bits of b cause that's enough for every shift possible for any witdh for example for 32 bit number the posible shifts can be caused by 5 bits as 2^5 = 32 similarly for ither 4,8,16 bits
                                                        /// also we have decided than shift operation  will be for a and shift will be decided by the lower bit of b not the human input


/// Level-1 ----> this is decode and conditioning ---- as we are using the shared adder for subtraction addition set less than and set less than unsigned so we need to have conditons when to give what input to the adder--- formula -- a + b_bar + sub ---here cub acts as a carry in so its 1 when sub is chosen and 0 when its not
//  b-bar is generated by the XOR property than b XOR 1 wil give b bar here we are xoring b with sub so when whenever sub is chose b XOR sub(1) is b_bar and adder: a+b_bar+sub(cin=1) so ==> b_bar + 1 gives -b and for adder we get a-b (which is subtraction)
assign  sub       = (Operation_ctrl==SUB) | (Operation_ctrl==SET_LESS_THAN) | (Operation_ctrl==SET_LESS_THAN_UNsigned); /// because set less than basically does is subtraction for comparison
assign  is_addsub = (Operation_ctrl==ADD) | (Operation_ctrl==SUB);
assign  b_bar     = b ^ {WIDTH{sub}}; // here we are duplication 1 bit of sub to the number width bit so that we get the correct xor of it with b (same width)

/// Level-2 ----> this is datapath units /// assigninh the operations
assign {carry_out, add_out} = {1'b0, a} + {1'b0, b_bar} + sub; //so if it get overflow the extra bit will be stored in carryout--- we will use it to define the set less than unsinged operation 
assign and_out  = a & b;
assign or_out   = a | b;
assign xor_out  = a ^ b;
assign sll_out  = a << shift_amount; // its my decision that for shift operations a is the default chosen number it not on user request 
assign srl_out  = a >> shift_amount;
assign sra_out  = $signed(a) >>> shift_amount; // for sra we need to preserve the signed bit that's why we are making a as signed else all the input are unsigned by default
assign overflow = ~(a[WIDTH-1] ^ b_bar[WIDTH-1]) & (a[WIDTH-1] ^ add_out[WIDTH-1]);
assign slt      = add_out[WIDTH-1] ^ overflow;
assign sltu     = ~carry_out;

/// Level-3 ----> Result select
always @(*) begin
    case (Operation_ctrl)
        ADD, SUB                : result = add_out;
        AND_Op                  : result = and_out; 
        OR_Op                   : result = or_out;
        XOR_op                  : result = xor_out;
        SHIFT_LEFT_LOGICAl      : result = sll_out;
        SHIFT_RIGHT_LOGICAL     : result = srl_out;  
        SHIFT_RIGHT_ARITHEMATIC : result = sra_out;
        SET_LESS_THAN           : result = {{(WIDTH-1){1'b0}}, slt}; 
        SET_LESS_THAN_UNsigned  : result = {{(WIDTH-1){1'b0}}, sltu};
        default                 : result = {WIDTH{1'b0}};               
    endcase
end

/// Level-4 ----> FLags
assign zero_flag = ~|result;
assign overflow_flag = overflow & is_addsub;
endmodule